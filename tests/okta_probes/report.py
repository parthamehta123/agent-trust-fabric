"""The preflight report: one row per probe, safe to paste into ``docs/architecture.md``.

Evidence is claim *names*, value *shapes*, booleans and OAuth error codes, never token material.
Anything token- or key-shaped is refused at record time, not filtered out later.
"""

from __future__ import annotations

import datetime as dt
import pathlib
import re
from dataclasses import dataclass, field
from typing import Final

_FORBIDDEN: Final = (
    re.compile(r"eyJ[A-Za-z0-9_-]{5,}\.[A-Za-z0-9_-]{5,}"),  # a JWS/JWT
    re.compile(r"-----BEGIN"),  # PEM
    re.compile(r"[A-Za-z0-9_-]{120,}"),  # any long opaque blob (an opaque token, a code)
)
MAX_VALUE_CHARS: Final = 200

EvidenceValue = str | bool | int | list[str]


def safe(value: EvidenceValue) -> str:
    text = ", ".join(value) if isinstance(value, list) else str(value)
    if len(text) > MAX_VALUE_CHARS or any(p.search(text) for p in _FORBIDDEN):
        raise ValueError("refusing to record token- or key-shaped evidence")
    return text.replace("|", "/").replace("\n", " ")


@dataclass
class Row:
    assumption: str
    probe: str
    outcome: str
    evidence: dict[str, str] = field(default_factory=dict)


@dataclass
class Report:
    rows: list[Row] = field(default_factory=list)

    def add(self, assumption: str, probe: str, outcome: str, evidence: dict[str, str]) -> None:
        self.rows.append(Row(assumption, probe, safe(outcome), evidence))

    def markdown(self, today: dt.date) -> str:
        lines = [
            f"# Okta preflight ({today.isoformat()})",
            "",
            "Generated by `make okta-probes`. **fail** means Okta refuted the assumption;"
            " **skipped** means the probe didn't run (reason given).",
            "",
            "| Assumption | Probe | Result | Evidence |",
            "|---|---|---|---|",
        ]
        for r in sorted(self.rows, key=lambda r: (r.assumption, r.probe)):
            ev = "; ".join(f"{k}: {v}" for k, v in sorted(r.evidence.items())) or "-"
            lines.append(f"| {r.assumption} | `{r.probe}` | {r.outcome} | {ev} |")
        return "\n".join(lines) + "\n"

    def write(self, path: pathlib.Path, today: dt.date | None = None) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.markdown(today or dt.datetime.now(dt.UTC).date()))
